"""Render benchmark/results/perf/perf_v1.json as Markdown tables (docs/PERFORMANCE.md uses them).

    python benchmark/perf/report.py [perf_v1.json] [out.md]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

IN = Path("benchmark/results/perf/perf_v1.json")
OUT = Path("benchmark/results/perf/perf_v1_tables.md")


def ms(v) -> str:
    if v is None:
        return "–"
    if v >= 1000:
        return f"{v / 1000:,.2f} s"
    if v >= 10:
        return f"{v:,.0f} ms"
    if v >= 1:
        return f"{v:.1f} ms"
    if v >= 0.01:
        return f"{v:.2f} ms"
    return f"{v * 1000:.1f} µs"


def cell(sysrec: dict | None, p95: bool = False) -> str:
    if not sysrec:
        return "–"
    if sysrec["status"] != "ok":
        return f"**{sysrec['status']}**"
    s = ms(sysrec["median_ms"])
    if p95 and sysrec.get("p95_ms") is not None:
        s += f" ({ms(sysrec['p95_ms'])})"
    return s


def render(d: dict) -> str:
    env = d["environment"]
    eng = env["engine"]
    out = [f"<!-- generated by benchmark/perf/report.py from {IN.as_posix()} -->", ""]
    out += ["### Environment", "", "| | |", "| --- | --- |",
            f"| Engine | gql-core {eng['version']}, {eng['source']} from {eng.get('installed_from', '?')} (`{eng['location']}`) |",
            f"| Installed files (RECORD sha256) | `{eng.get('record_sha256', '?')[:16]}…` |",
            f"| Harness commit | `{env['git_commit']}` |",
            f"| Python | {env['implementation']} {env['python']} |", f"| OS | {env['os']} |",
            f"| CPU | {env['cpu']}, {env['logical_cpus']} logical CPUs (single-threaded runs) |",
            f"| RAM | {env['ram_gb']} GB |", f"| Baselines | SQLite {env['sqlite']} (in memory), NetworkX {env['networkx']} |",
            f"| Workloads / generator | v{d['workload_version']} / v{d['generator_version']}, seed {d['seed']} |", ""]

    out += ["### Graphs, load time and memory", "",
            "| Nodes | Relationships | KNOWS out-degree mean / p99 / max | GQL-Core load (`from_dict`) | GQL-Core load (`add_node`/`add_edge`) | SQLite load + indexes | NetworkX load |",
            "| ---: | ---: | --- | ---: | ---: | ---: | ---: |"]
    for s in d["sizes"]:
        g, ld, k = s["graph"], s["load"], s["graph"]["knows_out_degree"]
        out.append(f"| {g['nodes']:,} | {g['edges']:,} | {k['mean']} / {k['p99']} / {k['max']} | "
                   f"{ld['gql_core_from_dict_s']:.2f} s | {ld['gql_core_add_node_edge_s']:.2f} s | "
                   f"{ld['sqlite_memory_with_indexes_s']:.2f} s | {ld['networkx_s']:.2f} s |")
    mem = {(m["size"], m["system"]): m for m in d.get("memory", [])}
    if mem:
        out += ["", "| Nodes | GQL-Core | SQLite (in memory) | NetworkX | GQL-Core bytes per node or relationship |",
                "| ---: | ---: | ---: | ---: | ---: |"]
        for n in sorted({k[0] for k in mem}):
            def mb(sysname):
                m = mem.get((n, sysname))
                return f"{m['rss_delta_mb']:,.0f} MB" if m else "–"
            gq = mem.get((n, "gql_core"))
            out.append(f"| {n:,} | {mb('gql_core')} | {mb('sqlite')} | {mb('networkx')} | "
                       f"{gq['bytes_per_node_or_edge']:,.0f} |" if gq else f"| {n:,} | – | – | – | – |")

    ids = list(d["sizes"][0]["workloads"])
    for s in d["sizes"]:
        n = s["graph"]["nodes"]
        out += ["", f"### Latency, {n:,} nodes / {s['graph']['edges']:,} relationships",
                "", "Median (p95 where at least 20 samples). Every cell is a verified-correct answer.", "",
                "| Workload | Category | Rows | GQL-Core | Python (dict indexes) | SQLite | NetworkX | GQL-Core path |",
                "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |"]
        for wid in ids:
            w = s["workloads"].get(wid)
            if not w:
                continue
            sy = w["systems"]
            path = (w.get("gql_core_stages") or {}).get("path", "inference" if "inference" in w["category"] else "–")
            out.append(f"| `{wid}` | {w['category']} | {w['rows_expected']:,} | {cell(sy.get('gql_core'), True)} | "
                       f"{cell(sy.get('python'))} | {cell(sy.get('sqlite'))} | {cell(sy.get('networkx'))} | {path} |")

    out += ["", "### Where GQL-Core's time goes (median per stage)", ""]
    for s in d["sizes"]:
        n = s["graph"]["nodes"]
        out += [f"**{n:,} nodes**", "", "| Workload | Path | Parse | Validate | Plan | Execute | Parse share |",
                "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
        for wid, w in s["workloads"].items():
            st = w.get("gql_core_stages")
            if not st or st["path"] == "typed_plan":
                continue
            total = st["parse"] + st["validate"] + st["plan"] + st["execute"]
            out.append(f"| `{wid}` | {st['path']} | {ms(st['parse'])} | {ms(st['validate'])} | {ms(st['plan'])} | "
                       f"{ms(st['execute'])} | {100 * st['parse'] / total:.1f}% |")
        out += [""]

    out += ["### Typed plan vs the same query in openCypher", "",
            "| Nodes | Typed plan | Build + validate | Execute | openCypher twin | Parse + validate + plan | Execute |",
            "| ---: | --- | ---: | ---: | --- | ---: | ---: |"]
    for s in d["sizes"]:
        for wid, twin in (("W12a_typed_filter", "W03a_filter_selective"), ("W12b_typed_hop", "W04a_hop_typical")):
            st = (s["workloads"].get(wid) or {}).get("gql_core_stages")
            ts = (s["workloads"].get(twin) or {}).get("gql_core_stages")
            if not st or not ts:
                continue
            out.append(f"| {s['graph']['nodes']:,} | `{wid}` | {ms(st['build'] + st['validate'])} | {ms(st['execute'])} | "
                       f"`{twin}` | {ms(ts.get('parse', 0) + ts.get('validate', 0) + ts.get('plan', 0))} | "
                       f"{ms(ts.get('execute'))} |")

    out += ["", "### Inference", "",
            "Transitive `SUBSIDIARY_OF` closure with `InferenceEngine` on the full benchmark graph "
            "(every node and relationship becomes a fact), and the derived-edge query against its variable-length twin:", "",
            "| Nodes | Derived facts | Inference | SQLite recursive CTE | NetworkX | Default `max_facts` derives | Materialize | `W14a` derived edges | `W14b` variable-length |",
            "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for s in d["sizes"]:
        w = s["workloads"].get("W13_transitive_inference")
        if not w:
            continue
        mat = s.get("materialize_inferred") or {}
        wa, wb = s["workloads"].get("W14a_derived_query", {}), s["workloads"].get("W14b_derived_via_var_len", {})
        derived = (w.get("expected") or [["?"]])[0][0]
        out.append(f"| {s['graph']['nodes']:,} | {derived:,} | {cell(w['systems'].get('gql_core'))} | "
                   f"{cell(w['systems'].get('sqlite'))} | {cell(w['systems'].get('networkx'))} | "
                   f"{w.get('default_engine_derived', '–'):,} | {mat.get('seconds', 0):.1f} s | "
                   f"{cell(wa.get('systems', {}).get('gql_core'))} | {cell(wb.get('systems', {}).get('gql_core'))} |")
    series = d.get("inference_scaling") or []
    if series:
        out += ["", "Inference alone, on hierarchies with no other facts:", "",
                "| Companies | Asserted edges | Derived facts | Correct | Median | Derived facts per second |",
                "| ---: | ---: | ---: | :---: | ---: | ---: |"]
        for r in series:
            rate = r["derived"] / (r["median_ms"] / 1000) if r.get("median_ms") else None
            out.append(f"| {r['companies']:,} | {r['asserted_edges']:,} | {r['derived']:,} | {'yes' if r['correct'] else 'no'} | "
                       f"{ms(r.get('median_ms'))} | {f'{rate:,.0f}' if rate else '–'} |")
    return "\n".join(out) + "\n"


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else IN
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    dst.write_text(render(json.loads(src.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"saved {dst}")


if __name__ == "__main__":
    main()
